// Generates app/src/generated/schema.ts and api/internal/schema/types_gen.go
// from schema/*.schema.json and schema/version.json, and copies the schema files
// to api/internal/schema/json/ for embedding.
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileFromFile } from 'json-schema-to-typescript';

const scriptsDir = dirname(fileURLToPath(import.meta.url));
const schemaDir = dirname(scriptsDir);
const repoRoot = dirname(schemaDir);
const tsOut = join(repoRoot, 'app/src/generated/schema.ts');
const goOut = join(repoRoot, 'api/internal/schema/types_gen.go');
const jsonOut = join(repoRoot, 'api/internal/schema/json');

const HEADER = 'Code generated by schema/scripts/generate.mjs. DO NOT EDIT.';

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));
const { goJsonschema } = readJson(join(scriptsDir, 'package.json')).config;
const { schemaVersion, minSupportedSchemaVersion } = readJson(join(schemaDir, 'version.json'));

const schemaFiles = readdirSync(schemaDir)
  .filter((name) => name.endsWith('.schema.json'))
  .sort()
  .map((name) => join(schemaDir, name));

async function generateTypeScript() {
  const parts = [];
  for (const file of schemaFiles) {
    parts.push(await compileFromFile(file, { bannerComment: '', cwd: schemaDir }));
  }
  const body = [
    `// ${HEADER}`,
    '',
    `export const SCHEMA_VERSION = ${schemaVersion};`,
    `export const MIN_SUPPORTED_SCHEMA_VERSION = ${minSupportedSchemaVersion};`,
    '',
    parts.map((part) => part.trim()).join('\n\n'),
    '',
  ].join('\n');
  mkdirSync(dirname(tsOut), { recursive: true });
  writeFileSync(tsOut, body);
}

function generateGo() {
  const code = execFileSync(
    'go',
    [
      'run',
      goJsonschema,
      '--package', 'schema',
      '--struct-name-from-title',
      '--capitalization', 'ID',
      '--tags', 'json',
      '--output', '-',
      ...schemaFiles,
    ],
    { cwd: repoRoot, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] },
  );
  const lines = code.split('\n');
  if (lines[0].startsWith('// Code generated')) lines.shift();
  const body = [
    `// ${HEADER}`,
    ...lines,
  ].join('\n').trimEnd() + [
    '',
    '',
    `const SchemaVersion = ${schemaVersion}`,
    '',
    `const MinSupportedSchemaVersion = ${minSupportedSchemaVersion}`,
    '',
  ].join('\n');
  mkdirSync(dirname(goOut), { recursive: true });
  writeFileSync(goOut, body);
}

function copySchemas() {
  rmSync(jsonOut, { recursive: true, force: true });
  mkdirSync(jsonOut, { recursive: true });
  for (const file of schemaFiles) {
    copyFileSync(file, join(jsonOut, basename(file)));
  }
}

await generateTypeScript();
generateGo();
copySchemas();
